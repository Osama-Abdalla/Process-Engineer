R = [1.2 1.3 1.4 1.5 1.7 2]; 
cost_S = [ 136500 142500 148800 155100 167100 185400]; 
po = polyfit(R,cost_S,2); 
R0 = 1:0.001:2; 
cost_S1 = polyval(po,R0); 
plot(R,cost_S,'o',R0,cost_S1); 
legend('2nd order interpolation','Reflux'); 
title('Reflux & cost'); 
xlabel('Reflux'); 
ylabel('cost ($)'); 
disp(po); 